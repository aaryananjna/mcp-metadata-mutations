#!/usr/bin/env python3
"""
Regenerate the results document from the dataset.

Every number in the writeup comes from here, so a number in the README can
never drift from the data that produced it. If you want to quote a figure,
quote it from reports/RESULTS.md, and if that figure looks wrong, rerun this
rather than editing the markdown.

    python3 report.py --data data --snapshot 2026-08-22

Takes a few minutes: it walks every consecutive version pair and re-derives
transitions from the stored blobs rather than trusting a cached count.
"""

import argparse
import json
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

from audit import classify_identifier_change
from classify import classify_owner_change, is_placeholder, owner
from diff import RUBRIC, transitions
from store import Store

# Buckets that survive subclassification. Everything else is an artifact of how
# a field is used (version strings inside identifiers, same-entity respellings)
# and must not be counted as a supply chain event.
DEFENSIBLE = {
    "package_identifier_changed": {"real_rename", "url_changed_beyond_version"},
    "repo_owner_changed": {"diverged_from_namespace", "unrelated"},
}


def pct(n, d):
    return 100.0 * n / d if d else 0.0


def build(store, snapshot):
    rows = store.states_at(snapshot)

    by_server = defaultdict(list)
    status = Counter()
    latest_n = 0
    schema = Counter()
    has_pkg = has_remote = has_repo = 0

    for r in rows:
        by_server[r["server_name"]].append(r)
        status[r["status"]] += 1
        latest_n += bool(r["is_latest"])
        schema[(r["schema_uri"] or "").rsplit("/", 2)[-2] if r["schema_uri"] else "none"] += 1
        if r["is_latest"]:
            rec = store.get_blob(r["content_hash"])
            has_pkg += bool(rec.get("packages"))
            has_remote += bool(rec.get("remotes"))
            has_repo += bool(rec.get("repository"))

    multi = {k: v for k, v in by_server.items() if len(v) > 1}
    pairs = sum(len(v) - 1 for v in by_server.values())

    counts = Counter()
    sub = defaultdict(Counter)
    placeholders = []

    for name, chain in by_server.items():
        for prev, cur in zip(chain, chain[1:]):
            a = store.get_blob(prev["content_hash"])
            b = store.get_blob(cur["content_hash"])
            ts = transitions(a, b)
            for t in ts:
                counts[t] += 1
                if t == "package_identifier_changed":
                    sub[t][classify_identifier_change(a, b)] += 1
                elif t == "repo_owner_changed":
                    bucket, _ = classify_owner_change(
                        name, (a.get("repository") or {}).get("url"),
                        (b.get("repository") or {}).get("url"))
                    sub[t][bucket] += 1

    for r in rows:
        rec = store.get_blob(r["content_hash"])
        url = (rec.get("repository") or {}).get("url")
        if url and is_placeholder(owner(url)):
            placeholders.append((r["server_name"], r["version"], r["status"], url))

    runs = store.db.execute(
        "SELECT snapshot, records, opened, closed, ok FROM runs "
        "WHERE ok=1 ORDER BY snapshot").fetchall()
    blobs = store.db.execute("SELECT COUNT(*), SUM(n_bytes) FROM blobs").fetchone()

    return dict(rows=len(rows), servers=len(by_server), multi=len(multi),
                pairs=pairs, status=status, latest=latest_n, counts=counts,
                sub=sub, placeholders=placeholders, runs=runs, blobs=blobs,
                has_pkg=has_pkg, has_remote=has_remote, has_repo=has_repo,
                schema=schema)


def render(d, snapshot, dangling=None):
    o = []
    w = o.append
    w("# Results\n")
    w("Generated by `report.py` from snapshot `%s` on %s.\n"
      % (snapshot, datetime.now(timezone.utc).strftime("%Y-%m-%d")))
    w("Do not edit by hand. Rerun `python3 report.py` instead.\n")

    w("\n## 1. Population\n")
    w("| Measure | Value |")
    w("|---|---|")
    w("| Distinct servers | %s |" % f"{d['servers']:,}")
    w("| Version records (all versions ever published) | %s |" % f"{d['rows']:,}")
    w("| Mean versions per server | %.2f |" % (d["rows"] / max(1, d["servers"])))
    w("| Servers with more than one version | %s (%.1f%%) |"
      % (f"{d['multi']:,}", pct(d["multi"], d["servers"])))
    w("| Consecutive version pairs analysed | %s |" % f"{d['pairs']:,}")
    for k, v in d["status"].most_common():
        w("| Version records with status `%s` | %s |" % (k, f"{v:,}"))
    w("\nCurrent versions by distribution channel:\n")
    w("| Channel | Current versions |")
    w("|---|---|")
    w("| Has `packages[]` | %s |" % f"{d['has_pkg']:,}")
    w("| Has `remotes[]` | %s |" % f"{d['has_remote']:,}")
    w("| Has `repository` | %s |" % f"{d['has_repo']:,}")
    w("\nServers exposed only through `remotes[]` have a runtime surface the "
      "registry cannot observe, which bounds what this study can claim. See "
      "Limitations.\n")

    w("\n## 2. Version-to-version transitions\n")
    w("Raw detector firings across %s consecutive version pairs. "
      "**These are hypotheses, not findings.** See section 3.\n" % f"{d['pairs']:,}")
    w("| Transition | Count | Per 1,000 pairs | Severity | OWASP ASI | NIST AI RMF |")
    w("|---|---|---|---|---|---|")
    for t, n in d["counts"].most_common():
        sev, asi, nist = RUBRIC.get(t, ("info", "-", "-"))
        w("| `%s` | %s | %.2f | %s | %s | %s |"
          % (t, f"{n:,}", 1000.0 * n / max(1, d["pairs"]), sev, asi, nist))

    w("\n## 3. Detector correction\n")
    w("Every detector that fired more than a hundred times was subclassified "
      "and audited against the underlying strings. Both lost the large "
      "majority of their firings to artifacts. The correction ratio is itself "
      "a result about how noisy naive scanning of this ecosystem is.\n")
    w("| Detector | Raw | Defensible | Retained |")
    w("|---|---|---|---|")
    for t, buckets in d["sub"].items():
        raw = sum(buckets.values())
        keep = sum(n for k, n in buckets.items() if k in DEFENSIBLE.get(t, set()))
        w("| `%s` | %s | %s | %.1f%% |"
          % (t, f"{raw:,}", f"{keep:,}", pct(keep, raw)))

    for t, buckets in d["sub"].items():
        raw = sum(buckets.values())
        w("\n### `%s`\n" % t)
        w("| Subclass | Count | Share | Counted |")
        w("|---|---|---|---|")
        for k, n in buckets.most_common():
            keep = "yes" if k in DEFENSIBLE.get(t, set()) else "no"
            w("| `%s` | %s | %.1f%% | %s |" % (k, f"{n:,}", pct(n, raw), keep))

    w("\n## 4. Repository reference integrity\n")
    w("### Template placeholders\n")
    w("Version records whose `repository.url` contains an unedited template "
      "value. All are publicly listed.\n")
    w("| Server | Version | Status | URL |")
    w("|---|---|---|---|")
    for name, ver, st, url in sorted(d["placeholders"]):
        w("| `%s` | %s | %s | %s |" % (name, ver, st, url))
    w("\n%d records across %d servers.\n"
      % (len(d["placeholders"]), len({p[0] for p in d["placeholders"]})))

    if dangling:
        g = dangling
        w("\n### Publicly unresolvable repositories\n")
        w("| Measure | Value |")
        w("|---|---|")
        w("| Current versions scanned | %s |" % f"{g.get('records_scanned', 0):,}")
        w("| With no `repository` field | %s |" % f"{g.get('records_without_repo_field', 0):,}")
        w("| With a GitHub repository | %s |" % f"{g.get('records_with_github_repo', 0):,}")
        w("| Distinct GitHub owners | %s |" % f"{g.get('distinct_owners', 0):,}")
        w("| Owners not publicly resolvable | %s (%.2f%%) |"
          % (f"{g.get('unresolvable_owners', 0):,}",
             pct(g.get("unresolvable_owners", 0), g.get("distinct_owners", 1))))
        w("| Current versions affected | %s (%.2f%%) |"
          % (f"{g.get('affected_current_versions', 0):,}",
             pct(g.get("affected_current_versions", 0),
                 g.get("records_with_github_repo", 1))))
        w("\n**Caveat, load-bearing.** A 404 from the GitHub users API means "
          "\"not visible to this token\", which covers genuinely free names, "
          "restricted or enterprise-managed orgs, and transient blocks. "
          "Manual control testing confirmed both states are present in this "
          "set. The defensible claim is that these repositories are not "
          "publicly readable, not that the names are registerable.\n")

    w("\n## 5. Collection integrity\n")
    w("| Snapshot | Records | States opened | States closed |")
    w("|---|---|---|---|")
    for snap, rec, op, cl, _ in d["runs"]:
        w("| %s | %s | %s | %s |"
          % (snap, f"{rec or 0:,}", f"{op or 0:,}", f"{cl or 0:,}"))
    n_blobs, n_bytes = d["blobs"]
    w("\nContent-addressed blobs: %s, %.1f MB uncompressed. "
      "Verify with `python3 verify.py --data data`.\n"
      % (f"{n_blobs:,}", (n_bytes or 0) / 1e6))
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data")
    ap.add_argument("--snapshot", required=True)
    ap.add_argument("--dangling", default="reports/dangling.json")
    ap.add_argument("--out", default="reports/RESULTS.md")
    args = ap.parse_args()

    store = Store(args.data)
    d = build(store, args.snapshot)

    dangling = None
    p = Path(args.dangling)
    if p.exists():
        dangling = json.load(open(p))

    text = render(d, args.snapshot, dangling)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    open(args.out, "w").write(text)
    print("wrote %s (%d lines)" % (args.out, text.count("\n")))


if __name__ == "__main__":
    main()